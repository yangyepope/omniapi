#!/usr/bin/env bash

# 这个脚本用于在 backend 项目中执行“静态检查”相关的一揽子任务（通常用于本地提交前检查或 CI）。
#
# 它做的事情（按顺序执行，任何一步失败都会直接失败退出）：
# 1) mypy app                 -> Python 类型检查（typecheck）
# 2) ruff check app           -> Python 代码规范/潜在问题检查（lint）
# 3) ruff format app --check  -> Python 代码格式检查（只检查，不改文件）
#
# ---------------------------------------------------------------------------
# 解释：为什么用 #!/usr/bin/env bash
# ---------------------------------------------------------------------------
# 这是 shebang，用来告诉系统“用哪个解释器执行这个文件”。
# - /usr/bin/env bash 的意思是：通过 env 在当前 PATH 里查找 bash。
# - 这样写比写死 /bin/bash 更通用（不同系统 bash 路径可能不同，但 PATH 通常会包含它）。
#
# ---------------------------------------------------------------------------
# 解释：set -e
# ---------------------------------------------------------------------------
# set -e 表示“遇到错误立即退出”：
# - shell 中命令退出码 0 表示成功，非 0 表示失败。
# - 开启 -e 后，只要某一步返回非 0，脚本立刻退出，后续命令不会再执行。
# - 这样做的好处是：CI 日志会更聚焦地指向第一个失败点，避免继续跑出更多噪音。
#
# ---------------------------------------------------------------------------
# 解释：set -x
# ---------------------------------------------------------------------------
# set -x 表示“命令回显（trace）”：
# - 执行每一行命令前，会把该命令打印出来（通常以 + 作为前缀）。
# - 这样能在本地/CI 日志中清楚看到脚本实际执行了什么，便于排障和复现。
#
# ---------------------------------------------------------------------------
# 解释：mypy app（类型检查）
# ---------------------------------------------------------------------------
# mypy 会对 app/ 目录做静态类型检查（基于类型标注与项目配置）。
# 典型能发现：
# - 函数返回值类型不匹配
# - Optional/None 的不安全使用
# - 泛型缺少类型参数（例如 list vs list[str]）
# - 函数调用的参数类型不匹配
# 等等。
#
# 注意：本项目在 pyproject.toml 中启用了严格模式（[tool.mypy] strict=true），
# 因此对类型问题更敏感，CI 也更容易因为类型不严谨而失败。
#
# ---------------------------------------------------------------------------
# 解释：ruff check app（lint 检查）
# ---------------------------------------------------------------------------
# ruff check 会对 app/ 执行 lint 检查，覆盖：
# - 未使用的 import / 变量
# - import 顺序/分组
# - 一些可疑写法/潜在 bug（取决于配置启用的规则）
# - 语法升级建议（pyupgrade）等
#
# 这个脚本只做“检查”，不做自动修复。
# 如果要自动修复一部分问题，需要手动运行：ruff check app --fix
#
# ---------------------------------------------------------------------------
# 解释：ruff format app --check（格式检查但不修改）
# ---------------------------------------------------------------------------
# ruff format 是格式化工具：
# - ruff format app           会直接改文件，把格式调整到统一规范
# - ruff format app --check   只检查是否符合格式，不会修改文件
#
# 在 --check 模式下，如果发现某些文件“不符合格式”，ruff 会输出：
# - Would reformat: xxx.py
# 并返回非 0 退出码；配合 set -e，会让脚本直接失败。
#
# 这样做的目的通常是：
# - CI 强制要求代码必须已格式化
# - 避免 PR/提交里出现大量无意义的格式 diff
#
# ---------------------------------------------------------------------------
# 运行方式（常见）
# ---------------------------------------------------------------------------
# - 在 backend 目录下直接运行（前提：当前环境能找到 mypy/ruff）：
#     bash scripts/lint.sh
#
# - 在 docker compose 的 backend 容器中运行（本项目常见方式）：
#     docker compose exec -T backend bash -lc 'export PATH=/app/.venv/bin:$PATH; bash scripts/lint.sh'
#
set -e
set -x

mypy app
ruff check app
ruff format app --check
